"""One release identity derived from the integrated RenderDoc headers and Bread revision.

This module uses only the standard library; it runs before dependency restoration.
It never fetches upstream, increments a revision, or touches a deployed app.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIG = "replaylab/packaging/RenderDocBread.package.json"
HEADER = "qrenderdoc/Code/BreadVersion.h"
SOURCES = {
    "replaylab/pyproject.toml": r'(?m)^version = "[^"\r\n]+"$',
    "replaylab/mcp_host/pyproject.toml": r'(?m)^version = "[^"\r\n]+"$',
    "replaylab/src/replaylab_agent/__init__.py": r'(?m)^__version__ = "[^"\r\n]+"$',
    "replaylab/mcp_host/src/version.py": r'(?m)^SERVICE_VERSION = "[^"\r\n]+"$',
}


def release_identity(repo=REPO, config=None):
    repo = Path(repo).resolve()
    config = config if config is not None else json.loads((repo / CONFIG).read_text(encoding="utf-8"))
    policy = config.get("versioning", {})
    if (policy.get("scheme") != "renderdoc-extension/v1"
            or policy.get("revisionPolicy") != "monotonic" or policy.get("displayPrefix") != "v"
            or policy.get("upstreamHeader") != "renderdoc/api/replay/version.h"):
        raise ValueError("Unsupported Bread version policy")
    revision = policy.get("extensionRevision")
    if type(revision) is not int or not 0 <= revision <= 65535:
        raise ValueError("extensionRevision must be an integer in 0..65535 (Windows version resource)")
    upstream = (repo / policy["upstreamHeader"]).read_text(encoding="utf-8")
    parts = []
    for name in ("MAJOR", "MINOR"):
        matches = re.findall(r"(?m)^#define RENDERDOC_VERSION_" + name + r"\s+([0-9]+)\s*$", upstream)
        if len(matches) != 1 or int(matches[0]) > 65535:
            raise ValueError("Missing or invalid integrated RenderDoc version: " + name)
        parts.append(int(matches[0]))
    version = ".".join(map(str, [*parts, revision]))
    return {"scheme": policy["scheme"], "upstreamVersion": ".".join(map(str, parts)),
            "extensionRevision": revision, "version": version, "displayVersion": "v" + version}


def generated_header(identity):
    major, minor, revision = map(int, identity["version"].split("."))
    return ('// Generated by replaylab/packaging/version_policy.py --write.\n'
            '#pragma once\n#include "../../renderdoc/api/replay/version.h"\n\n'
            '// i18n-ignore: Build/version identifiers, never translatable prose.\n'
            f'#define BREAD_VERSION_STRING "{identity["version"]}"\n'
            f'#define BREAD_FULL_VERSION_STRING "{identity["displayVersion"]}"\n'
            f'#define BREAD_FILE_VERSION {major}, {minor}, {revision}, 0\n'
            f'#define BREAD_FILE_VERSION_STRING "{identity["version"]}.0"\n'
            f'#if RENDERDOC_VERSION_MAJOR != {major} || RENDERDOC_VERSION_MINOR != {minor}\n'
            '#error Bread version is stale: run replaylab/packaging/version_policy.py --write\n'
            '#endif\n')


def synchronize(repo=REPO, *, write=False):
    repo = Path(repo)
    identity = release_identity(repo)
    expected = {HEADER: generated_header(identity)}
    # Validate the whole set before writing any generated source.
    for relative, pattern in SOURCES.items():
        content = (repo / relative).read_text(encoding="utf-8")
        matches = list(re.finditer(pattern, content))
        if len(matches) != 1:
            raise ValueError("Expected one version declaration: " + relative)
        assignment = matches[0].group().split(" = ", 1)[0]
        expected[relative] = re.sub(pattern, assignment + ' = "' + identity["version"] + '"', content)
    stale = [relative for relative, content in expected.items()
             if not (repo / relative).is_file() or (repo / relative).read_text(encoding="utf-8") != content]
    if write:
        for relative in stale:
            (repo / relative).write_text(expected[relative], encoding="utf-8", newline="\n")
    elif stale:
        raise ValueError("Bread version metadata is stale; run version_policy.py --write: " + ", ".join(stale))
    return identity


def validate_runtime_version(version, *, repo=REPO, config=None):
    identity = release_identity(repo, config)
    if version != identity["version"]:
        raise ValueError(f'Frozen runtime version {version!r} differs from release policy {identity["version"]}')
    return identity


def validate_gui_output(result, version):
    output = result.stdout + "\n" + result.stderr
    # The non-portable executable deliberately retains the legacy settings ID.
    found = re.findall(r"\b(?:RenderDocBread|q_render_soco_doc)\s+v?([0-9]+\.[0-9]+\.[0-9]+)\b", output)
    if result.returncode or found != [version]:
        raise ValueError(f"GUI --version must match Bread release {version}: {output.strip()[:500]}")


def validate_gui_version(gui, version):
    with tempfile.TemporaryDirectory(prefix="bread-version-check-") as temporary:
        env = {key: value for key, value in os.environ.items()
               if key in {"SystemRoot", "WINDIR", "TEMP", "TMP", "COMSPEC"}}
        for key in ("LOCALAPPDATA", "APPDATA", "HOME", "USERPROFILE", "RENDERDOC_CONFIG_DIR",
                    "REPLAYLAB_CONFIG_DIR", "REPLAYLAB_RUNTIME_DIR", "REPLAYLAB_INTERNAL_RUNTIME_DIR"):
            path = Path(temporary) / key.lower()
            path.mkdir()
            env[key] = str(path)
        env["PATH"] = os.pathsep.join([str(Path(gui).parent), str(Path(env.get("SystemRoot", "C:/Windows")) / "System32")])
        result = subprocess.run([str(gui), "--version"], cwd=Path(gui).parent, env=env, capture_output=True,
                            text=True, encoding="utf-8", errors="replace", timeout=30,
                            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    validate_gui_output(result, version)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=REPO)
    parser.add_argument("--write", action="store_true", help="Synchronize generated source versions")
    parser.add_argument("--check", action="store_true", help="Check all source versions without writing")
    args = parser.parse_args()
    if args.write and args.check:
        parser.error("Choose --write or --check")
    print(json.dumps(synchronize(args.repo, write=args.write), ensure_ascii=False))


if __name__ == "__main__":
    main()
